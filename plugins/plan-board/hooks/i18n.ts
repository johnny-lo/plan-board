const TABLES: Record<Lang, Record<Key, string>> = { en: EN, 'zh-TW': ZH_TW }

/** The label for `key` in `lang`, its `{name}` slots filled from `vars`. */
export function t(lang: Lang, key: Key, vars: Record<string, string | number> = {}): string {
  return TABLES[lang][key].replace(/\{(\w+)\}/g, (slot, name: string) => (Object.hasOwn(vars, name) ? String(vars[name]) : slot))
}

/** Whether `key` names a label, for keys built from the log's own words (a step status, an entry kind). */
export function hasKey(key: string): key is Key {
  return Object.hasOwn(EN, key)
}

/** Every key of `lang`'s table, for the test that checks both tables carry the same ones. */
export function keysOf(lang: Lang): string[] {
  return Object.keys(TABLES[lang])
}
